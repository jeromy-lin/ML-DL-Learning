# ============================================================
# Step 3：建立完工時間函數
# ============================================================

def 計算完工時間(機台數, 每日加班時數):

    每日總工時 = (
        每日正常工時
        + 每日加班時數
    )

    每日總產能 = (
        機台數
        * 單台每小時產能
        * 每日總工時
    )

    準備時間天數 = (
        固定準備時間
        / 每日正常工時
    )

    生產時間天數 = (
        訂單需求量
        / 每日總產能
    )

    完工時間天數 = (
        準備時間天數
        + 生產時間天數
    )

    return 完工時間天數


# ============================================================
# Step 4：建立總生產成本函數
# ============================================================

def 計算總生產成本(
    機台數,
    每日加班時數,
    完工時間天數
):

    作業人數 = (
        機台數
        * 每台機器配置人數
    )

    每日總工時 = (
        每日正常工時
        + 每日加班時數
    )

    材料成本 = (
        訂單需求量
        * 材料單價
    )

    機台啟用成本 = (
        機台數
        * 每台機器啟用成本
    )

    機台運轉成本 = (
        機台數
        * 完工時間天數
        * 每日總工時
        * 機器每小時成本
    )

    每日正常人工成本 = (
        作業人數
        * 每日正常工時
        * 每人每小時工資
    )

    每日加班人工成本 = (
        作業人數
        * 每日加班時數
        * 每人每小時工資
        * 加班工資倍率
    )

    正常人工總成本 = (
        每日正常人工成本
        * 完工時間天數
    )

    加班人工總成本 = (
        每日加班人工成本
        * 完工時間天數
    )

    總生產成本 = (
        材料成本
        + 機台啟用成本
        + 機台運轉成本
        + 正常人工總成本
        + 加班人工總成本
    )

    return {
        "材料成本": 材料成本,
        "機台啟用成本": 機台啟用成本,
        "機台運轉成本": 機台運轉成本,
        "正常人工成本": 正常人工總成本,
        "加班人工成本": 加班人工總成本,
        "總生產成本": 總生產成本
    }


